`timescale 1ns/1ps

module tb_fp_div;

    logic [63:0] a;
    logic [63:0] b;

    logic [63:0] result;


    // ============================================================
    // DUT
    // ============================================================

    fp_div #(
        .WIDTH(64)
    ) dut (
        .a(a),
        .b(b),
        .result(result)
    );


    // ============================================================
    // TEST TASK
    // ============================================================

    task automatic test_div(
        input [63:0] in_a,
        input [63:0] in_b,
        input [63:0] expected
    );

        begin

            a = in_a;
            b = in_b;

            #1;

            $display("---------------------------------------------");

            $display("A        = %h", a);
            $display("B        = %h", b);

            $display("Result   = %h", result);
            $display("Expected = %h", expected);


            if (result === expected)
                $display("STATUS   = PASS");
            else
                $display("STATUS   = FAIL");

        end

    endtask


    // ============================================================
    // TESTS
    // ============================================================

    initial begin

        $display("=============================================");
        $display("IEEE-754 FP64 DIVISION TEST");
        $display("=============================================");


        // ========================================================
        // BASIC DIVISION
        // ========================================================

        // 6 / 2 = 3
        test_div(
            64'h4018000000000000,
            64'h4000000000000000,
            64'h4008000000000000
        );


        // 10 / 2 = 5
        test_div(
            64'h4024000000000000,
            64'h4000000000000000,
            64'h4014000000000000
        );


        // 8 / 2 = 4
        test_div(
            64'h4020000000000000,
            64'h4000000000000000,
            64'h4010000000000000
        );


        // 1 / 2 = 0.5
        test_div(
            64'h3FF0000000000000,
            64'h4000000000000000,
            64'h3FE0000000000000
        );


        // 1 / 4 = 0.25
        test_div(
            64'h3FF0000000000000,
            64'h4010000000000000,
            64'h3FD0000000000000
        );


        // 7 / 2 = 3.5
        test_div(
            64'h401C000000000000,
            64'h4000000000000000,
            64'h400C000000000000
        );


        // ========================================================
        // NEGATIVE NUMBERS
        // ========================================================

        // -6 / 2 = -3
        test_div(
            64'hC018000000000000,
            64'h4000000000000000,
            64'hC008000000000000
        );


        // 6 / -2 = -3
        test_div(
            64'h4018000000000000,
            64'hC000000000000000,
            64'hC008000000000000
        );


        // -6 / -2 = +3
        test_div(
            64'hC018000000000000,
            64'hC000000000000000,
            64'h4008000000000000
        );


        // ========================================================
        // ZERO
        // ========================================================

        // 0 / 2 = +0
        test_div(
            64'h0000000000000000,
            64'h4000000000000000,
            64'h0000000000000000
        );


        // -0 / 2 = -0
        test_div(
            64'h8000000000000000,
            64'h4000000000000000,
            64'h8000000000000000
        );


        // ========================================================
        // DIVISION BY ZERO
        // ========================================================

        // 1 / 0 = +Inf
        test_div(
            64'h3FF0000000000000,
            64'h0000000000000000,
            64'h7FF0000000000000
        );


        // -1 / 0 = -Inf
        test_div(
            64'hBFF0000000000000,
            64'h0000000000000000,
            64'hFFF0000000000000
        );


        // ========================================================
        // INFINITY
        // ========================================================

        // Inf / 2 = Inf
        test_div(
            64'h7FF0000000000000,
            64'h4000000000000000,
            64'h7FF0000000000000
        );


        // -Inf / 2 = -Inf
        test_div(
            64'hFFF0000000000000,
            64'h4000000000000000,
            64'hFFF0000000000000
        );


        // 2 / Inf = 0
        test_div(
            64'h4000000000000000,
            64'h7FF0000000000000,
            64'h0000000000000000
        );


        // ========================================================
        // INVALID OPERATIONS
        // ========================================================

        // Inf / Inf = NaN
        test_div(
            64'h7FF0000000000000,
            64'h7FF0000000000000,
            64'h7FF8000000000001
        );


        // 0 / 0 = NaN
        test_div(
            64'h0000000000000000,
            64'h0000000000000000,
            64'h7FF8000000000001
        );


        // ========================================================
        // NaN
        // ========================================================

        // NaN / 1 = NaN
        test_div(
            64'h7FF8000000000001,
            64'h3FF0000000000000,
            64'h7FF8000000000001
        );


        // 1 / NaN = NaN
        test_div(
            64'h3FF0000000000000,
            64'h7FF8000000000001,
            64'h7FF8000000000001
        );


        // ========================================================
        // UNDERFLOW
        // ========================================================

        // Smallest normal / 2
        //
        // 2^-1022 / 2 = 2^-1023
        //
        // Result is subnormal.
        //
        test_div(
            64'h0010000000000000,
            64'h4000000000000000,
            64'h0008000000000000
        );


        // ========================================================
        // OVERFLOW
        // ========================================================

        // MAX_DOUBLE / 0.5 = Inf
        test_div(
            64'h7FEFFFFFFFFFFFFF,
            64'h3FE0000000000000,
            64'h7FF0000000000000
        );


        $display("=============================================");
        $display("DIVISION TESTS COMPLETED");
        $display("=============================================");

        $finish;

    end

endmodule