`timescale 1ns/1ps

module tb_fp_add;

    // ============================================================
    // Signals
    // ============================================================

    logic clk;
    logic rst;
    logic start;

    logic [63:0] a;
    logic [63:0] b;

    logic [63:0] result;
    logic busy;
    logic valid;


    // ============================================================
    // DUT
    // ============================================================

    fp_add #(
        .WIDTH(64)
    ) dut (
        .clk    (clk),
        .rst    (rst),
        .start  (start),
        .a      (a),
        .b      (b),
        .result (result),
        .busy   (busy),
        .valid  (valid)
    );


    // ============================================================
    // 100 MHz clock
    // 10 ns period
    // ============================================================

    initial begin
        clk = 1'b0;

        forever #5 clk = ~clk;
    end


    // ============================================================
    // Counters
    // ============================================================

    integer passed;
    integer failed;


    // ============================================================
    // TEST TASK
    // ============================================================

    task automatic test_add;

        input [63:0] test_a;
        input [63:0] test_b;
        input [63:0] expected;

        begin

            // ----------------------------------------------------
            // Wait until previous operation is finished
            // ----------------------------------------------------

            @(negedge clk);

            while (busy)
                @(negedge clk);


            // ----------------------------------------------------
            // Apply inputs
            // ----------------------------------------------------

            a = test_a;
            b = test_b;


            // ----------------------------------------------------
            // Generate one-cycle START pulse
            // ----------------------------------------------------

            start = 1'b1;

            @(negedge clk);

            start = 1'b0;


            // ----------------------------------------------------
            // Wait for pipelined result
            // ----------------------------------------------------

            wait (valid);

            // Allow NBA updates to settle
            #1;


            // ----------------------------------------------------
            // Compare
            // ----------------------------------------------------

            if (result === expected) begin

                $display(
                    "PASS : A=%h  B=%h  RESULT=%h",
                    test_a,
                    test_b,
                    result
                );

                passed = passed + 1;

            end

            else begin

                $display(
                    "FAIL : A=%h  B=%h  RESULT=%h  EXPECTED=%h",
                    test_a,
                    test_b,
                    result,
                    expected
                );

                failed = failed + 1;

            end


            // ----------------------------------------------------
            // Wait until VALID goes low before next test
            // ----------------------------------------------------

            @(negedge clk);

        end

    endtask


    // ============================================================
    // TEST SEQUENCE
    // ============================================================

    initial begin

        // --------------------------------------------------------
        // Initial values
        // --------------------------------------------------------

        a      = 64'd0;
        b      = 64'd0;
        start  = 1'b0;

        rst    = 1'b1;

        passed = 0;
        failed = 0;


        // --------------------------------------------------------
        // Reset
        // --------------------------------------------------------

        repeat (2)
            @(negedge clk);

        rst = 1'b0;


        // ========================================================
        // BASIC ADDITION
        // ========================================================

        // 1.0 + 2.0 = 3.0
        test_add(
            64'h3FF0000000000000,
            64'h4000000000000000,
            64'h4008000000000000
        );


        // 2.0 + 2.0 = 4.0
        test_add(
            64'h4000000000000000,
            64'h4000000000000000,
            64'h4010000000000000
        );


        // 1.5 + 2.5 = 4.0
        test_add(
            64'h3FF8000000000000,
            64'h4004000000000000,
            64'h4010000000000000
        );


        // 10.0 + 20.0 = 30.0
        test_add(
            64'h4024000000000000,
            64'h4034000000000000,
            64'h403E000000000000
        );


        // ========================================================
        // DIFFERENT EXPONENTS
        // ========================================================

        // 1.0 + 0.5 = 1.5
        test_add(
            64'h3FF0000000000000,
            64'h3FE0000000000000,
            64'h3FF8000000000000
        );


        // 8.0 + 0.25 = 8.25
        test_add(
            64'h4020000000000000,
            64'h3FD0000000000000,
            64'h4020800000000000
        );


        // ========================================================
        // SUBTRACTION THROUGH SIGN
        // ========================================================

        // 5.0 + (-2.0) = 3.0
        test_add(
            64'h4014000000000000,
            64'hC000000000000000,
            64'h4008000000000000
        );


        // 2.0 + (-5.0) = -3.0
        test_add(
            64'h4000000000000000,
            64'hC014000000000000,
            64'hC008000000000000
        );


        // 100.0 + (-25.0) = 75.0
        test_add(
            64'h4059000000000000,
            64'hC039000000000000,
            64'h4052C00000000000
        );


        // ========================================================
        // CANCELLATION
        // ========================================================

        // 1.0 + (-1.0) = +0
        test_add(
            64'h3FF0000000000000,
            64'hBFF0000000000000,
            64'h0000000000000000
        );


        // ========================================================
        // ZERO
        // ========================================================

        // 0 + 5 = 5
        test_add(
            64'h0000000000000000,
            64'h4014000000000000,
            64'h4014000000000000
        );


        // -0 + 5 = 5
        test_add(
            64'h8000000000000000,
            64'h4014000000000000,
            64'h4014000000000000
        );


        // ========================================================
        // INFINITY
        // ========================================================

        // +Inf + 1 = +Inf
        test_add(
            64'h7FF0000000000000,
            64'h3FF0000000000000,
            64'h7FF0000000000000
        );


        // -Inf + 1 = -Inf
        test_add(
            64'hFFF0000000000000,
            64'h3FF0000000000000,
            64'hFFF0000000000000
        );


       


        // ========================================================
        // SUBNORMAL TESTS
        // ========================================================

        // Minimum subnormal + minimum subnormal
        // = 2 × minimum subnormal
        test_add(
            64'h0000000000000001,
            64'h0000000000000001,
            64'h0000000000000002
        );


        // Minimum normal + maximum subnormal
        test_add(
            64'h0010000000000000,
            64'h000FFFFFFFFFFFFF,
            64'h001FFFFFFFFFFFFF
        );


        // Minimum normal - maximum subnormal
        // = minimum subnormal
        test_add(
            64'h0010000000000000,
            64'h800FFFFFFFFFFFFF,
            64'h0000000000000001
        );


        // ========================================================
        // ROUNDING TEST
        // ========================================================

        // 1.0 + 2^-53
        //
        // Exactly halfway between representable values.
        // Round-to-nearest-even keeps 1.0.
        //
        test_add(
            64'h3FF0000000000000,
            64'h3CA0000000000000,
            64'h3FF0000000000000
        );


        // ========================================================
        // FINAL REPORT
        // ========================================================

        $display("");
        $display("==============================================");
        $display("       IEEE-754 FP64 ADD TEST COMPLETE");
        $display("==============================================");
        $display("PASSED = %0d", passed);
        $display("FAILED = %0d", failed);
        $display("TOTAL  = %0d", passed + failed);
        $display("==============================================");


        if (failed == 0)

            $display("STATUS = PASS");

        else

            $display("STATUS = FAIL");


        // Allow waveform/output to settle
        #20;

        $finish;

    end

endmodule