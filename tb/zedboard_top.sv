module zedboard_top (
    input  logic [1:0] sw,
    output logic [7:0] led
);

    // ============================================================
    // FP64 inputs
    // ============================================================
    //
    // A = 1.0
    // IEEE-754:
    // 1.0 = 3FF0000000000000
    //
    // B = 2.0
    // IEEE-754:
    // 2.0 = 4000000000000000
    //
    // ============================================================

    logic [63:0] a;
    logic [63:0] b;

    assign a = 64'h3FF0000000000000;
    assign b = 64'h4000000000000000;


    // ============================================================
    // Operation
    // ============================================================
    //
    // sw[1:0]
    //
    // 00 -> ADD
    // 01 -> SUB
    // 10 -> MUL
    // 11 -> DIV
    //
    // ============================================================

    logic [1:0] op;

    assign op = sw;


    // ============================================================
    // ALU result
    // ============================================================

    logic [63:0] result;


    // ============================================================
    // Your existing IEEE-754 ALU
    // ============================================================

    fp_alu #(
        .WIDTH(64)
    ) u_fp_alu (
        .a      (a),
        .b      (b),
        .op     (op),
        .result  (result)
    );


    // ============================================================
    // Display result on ZedBoard LEDs
    // ============================================================
    //
    // Only 8 LEDs are available, so display the lowest 8 bits.
    //
    // This is only for the FIRST hardware test.
    // Later we will use UART to display the complete 64-bit result.
    //
    // ============================================================

    assign led = result[7:0];

endmodule